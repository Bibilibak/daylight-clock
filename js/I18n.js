var lang = "pl";

// t("klucz") zwraca tekst w aktualnym języku (awaryjnie po angielsku, a dla polskiego po polsku)
function t(key) {
  return (I18N[lang] && I18N[lang][key]) || (lang !== "pl" && I18N.en[key]) || I18N.pl[key] || key
}

// Słowo "dzień/dni" w odpowiedniej formie liczby mnogiej (ukraiński i arabski mają ich więcej niż dwie).
// Brakująca forma -> dayMany.
function dayKey(n) {
  var c = n === 1 ? "one" : "other";
  try { c = new Intl.PluralRules(lang).select(n) } catch (e) { c = n === 1 ? "one" : "many" }   // stara przeglądarka: zwykła liczba mnoga
  var k = { one: "dayOne", two: "dayTwo", few: "dayFew", many: "dayMany", other: "dayOther" }[c] || "dayMany";
  return I18N[lang] && I18N[lang][k] ? k : (c === "one" ? "dayOne" : "dayMany")
}

// Locale do dat i liczb: arabski z cyframi łacińskimi, jak reszta strony
function loc() { return lang === "ar" ? "ar-u-nu-latn" : lang }

// Język: zapisany wybór -> język przeglądarki -> angielski
function detectLang() {
  try {
    var s = localStorage.getItem("lang");
    if (s && I18N[s]) return s
  } catch (e) {}
  var n = (navigator.language || "en").slice(0, 2).toLowerCase();
  return I18N[n] ? n : "en"
}

// Ustawia język i podmienia wszystkie teksty oznaczone data-i18n*
function setLang(l) {
  if (!I18N[l]) l = "en";
  lang = l;
  try { localStorage.setItem("lang", l) } catch (e) {}
  document.documentElement.lang = l;
  document.documentElement.dir = l === "ar" ? "rtl" : "ltr";   // arabski: od prawej do lewej
  document.title = t("title");
  document.querySelectorAll("[data-i18n]").forEach(function (el) { el.textContent = t(el.getAttribute("data-i18n")) });
  document.querySelectorAll("[data-i18n-ph]").forEach(function (el) { el.placeholder = t(el.getAttribute("data-i18n-ph")) });
  document.querySelectorAll("[data-i18n-aria]").forEach(function (el) { el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria"))) });
  document.querySelectorAll("#langList [data-lang]").forEach(function (o) {   // lista języków: zaznacz wybrany, podpisz przycisk
    var on = o.getAttribute("data-lang") === l;
    o.setAttribute("aria-selected", on ? "true" : "false");
    if (on && document.getElementById("langCur")) document.getElementById("langCur").textContent = o.textContent
  });
}
